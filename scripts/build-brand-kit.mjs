const COL_W = (BOARD_W - M * 2 - GUT * 2) / 3;
const ROW_H = (BOARD_H - M * 2 - GUT * 2) / 3;

const col = (i) => M + i * (COL_W + GUT);
const row = (j) => M + j * (ROW_H + GUT);

/** A board panel: a plate on the bond, ruled, with a mono label in the corner. */
function panel(i, j, number, title, body) {
  const x = col(i);
  const y = row(j);
  return [
    `  <rect x="${x}" y="${y}" width="${COL_W}" height="${ROW_H}" fill="${D["bond-2"]}" stroke="${D.rule}" stroke-width="1"/>`,
    `  <text x="${x + 28}" y="${y + 46}" font-family="${MONO}" font-size="18" font-weight="500" letter-spacing="2.6" fill="${D["ink-3"]}">${number} ${esc(title).toUpperCase()}</text>`,
    body(x, y),
  ].join("\n");
}

/** The mark, placed by centre at (cx, cy) at a given pixel height. */
function markAt(cx, cy, height, opts = {}) {
  const scale = height / 512;
  const gx = cx - 256 * scale;
  const gy = cy - 256 * scale;
  const box = opts.tile
    ? `  <rect x="16" y="16" width="480" height="480" rx="104" fill="${D.bond}" stroke="${D.rule}" stroke-width="3"/>`
    : "";
  return [
    `  <g transform="translate(${gx.toFixed(2)} ${gy.toFixed(2)}) scale(${scale.toFixed(4)})">`,
    box,
    glyph(opts),
    "  </g>",
  ].join("\n");
}

/** Typeset wordmark — never baked into a logo file (BRAND.md §3.5). */
function wordmark(x, y, size, fill = D.ink) {
  return `  <text x="${x}" y="${y}" font-family="${SANS}" font-size="${size}" font-weight="600" fill="${fill}">DocHarvest</text>`;
}

