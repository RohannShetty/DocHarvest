/** The one source of truth for the package version in drawn assets. */
function packageVersion() {
  const pyproject = readFileSync(join(root, "pyproject.toml"), "utf8");
  const hit = /^version\s*=\s*"([^"]+)"/m.exec(pyproject);
  if (!hit) throw new Error("pyproject.toml has no [project] version to draw");
  return hit[1];
}

